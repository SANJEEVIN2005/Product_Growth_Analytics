-- ============================================================
-- 04_create_clean_events.sql
-- Run as growth_user in XEPDB1
-- Transforms raw staging events into a clean, typed events table
-- with real DATE and TIMESTAMP WITH TIME ZONE columns.
-- ============================================================

SET DEFINE OFF;
SET TIMING ON;
SET PAGESIZE 50 LINESIZE 120;

-- Drop clean events table if exists
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE events PURGE';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Create clean events table
CREATE TABLE events (
    event_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_timestamp   NUMBER(18) NOT NULL,
    event_time      TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    event_date      DATE NOT NULL,
    visitorid       NUMBER(10) NOT NULL,
    event_type      VARCHAR2(20) NOT NULL,
    itemid          NUMBER(10) NOT NULL,
    transactionid   NUMBER(10)
);

-- Transforming and Loading events from stg_events
INSERT /*+ APPEND */ INTO events (
    raw_timestamp,
    event_time,
    event_date,
    visitorid,
    event_type,
    itemid,
    transactionid
)
SELECT
    timestamp,
    TIMESTAMP '1970-01-01 00:00:00.000 UTC' + NUMTODSINTERVAL(timestamp / 1000, 'SECOND'),
    TO_DATE('1970-01-01', 'YYYY-MM-DD') + (timestamp / 86400000),
    visitorid,
    TRIM(event),
    itemid,
    transactionid
FROM stg_events;

COMMIT;

-- Creating Performance Indexes for Analytical Stages
CREATE INDEX idx_events_visitor ON events (visitorid, event_time);
CREATE INDEX idx_events_date ON events (event_date);
CREATE INDEX idx_events_type ON events (event_type);
CREATE INDEX idx_events_item ON events (itemid);

-- Verification of clean events table
SELECT COUNT(*) AS total_clean_events,
       MIN(event_date) AS min_date,
       MAX(event_date) AS max_date,
       COUNT(DISTINCT visitorid) AS distinct_visitors,
       COUNT(DISTINCT itemid) AS distinct_items,
       COUNT(DISTINCT transactionid) AS distinct_transactions
FROM events;
